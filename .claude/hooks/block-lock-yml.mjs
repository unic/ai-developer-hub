#!/usr/bin/env node
// PreToolUse hook: blocks edits to generated gh-aw .lock.yml files.
// These are regenerated from the sibling .md by `gh aw compile`; hand-edits
// are silently overwritten on the next compile.
import { readFileSync } from "node:fs";

let input;
try {
  input = JSON.parse(readFileSync(0, "utf-8"));
} catch {
  process.exit(0);
}

const filePath = input?.tool_input?.file_path || "";
const normalized = filePath.replace(/\\/g, "/");

if (/\.github\/workflows\/[^/]+\.lock\.yml$/.test(normalized)) {
  const mdSibling = normalized.replace(/\.lock\.yml$/, ".md");
  process.stderr.write(
    `Refusing to edit ${filePath}.\n\n` +
      `This file is generated by 'gh aw compile' from ${mdSibling}.\n` +
      `Edit the .md source instead, then run 'gh aw compile' to regenerate the .lock.yml — ` +
      `both should land in the same commit.\n`,
  );
  process.exit(2);
}

process.exit(0);
